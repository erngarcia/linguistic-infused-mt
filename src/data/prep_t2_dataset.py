# src/data/prep_t2_dataset.py
"""
Builds the linguistically-infused fine-tuning dataset (T2) from a raw JSONL file
generated by the augmentation script.

Each record contains:
  - <instruction> (linguistic reasoning instruction)
  - <source_text> ... </source_text>
  - <reasoning> ... </reasoning>
  - <translation> ... </translation>

This script validates, normalizes, deduplicates, and outputs a clean JSONL file
ready for LoRA fine-tuning.

Usage:
    python src/data/prep_t2_dataset.py \
        --raw_jsonl data/augmented/en_es_raw.jsonl \
        --out_dir data/prepared/en_es \
        --dedupe_by_source \
        --on_missing_translation wrap_last_para
"""

from __future__ import annotations
import argparse, json, re, random, logging
from pathlib import Path
from typing import Dict, List, Optional


TAG_BLOCKS = ["source_text", "reasoning", "translation"]
random.seed(42)
logging.basicConfig(format="[%(levelname)s] %(message)s", level=logging.INFO)

def load_jsonl(path: Path) -> List[Dict]:
    """Load JSONL file safely."""
    rows = []
    with path.open("r", encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError as e:
                raise SystemExit(f"[ERROR] Invalid JSON on line {i} in {path}:\n{line[:200]}\n{e}")
    logging.info(f"Loaded {len(rows)} raw records from {path}")
    return rows


def normalize_whitespace_keep_newlines(s: str) -> str:
    """Collapse spaces but preserve newlines."""
    s = re.sub(r"[ \t]+", " ", s)
    s = re.sub(r"[ \t]*\n[ \t]*", "\n", s)
    return s.strip()


def ensure_block_lines(text: str) -> str:
    """Ensure <tag> and </tag> start on new lines."""
    for tag in TAG_BLOCKS:
        text = re.sub(fr"<{tag}>\s*", fr"<{tag}>\n", text, flags=re.I)
        text = re.sub(fr"\s*</{tag}>", fr"\n</{tag}>", text, flags=re.I)
    text = re.sub(r"\n{3,}", "\n\n", text)
    lines = [ln.strip() for ln in text.splitlines()]
    return "\n".join(lines).strip()


def extract_block(text: str, tag: str) -> Optional[str]:
    """Extract content inside <tag> ... </tag>."""
    m = re.search(fr"<{tag}>\s*(.*?)\s*</{tag}>", text, flags=re.S | re.I)
    return m.group(1).strip() if m else None


def wrap_last_paragraph_as_translation(out: str) -> tuple[str, bool]:
    """Heuristic: wrap the last non-empty paragraph as <translation>…</translation>."""
    parts = [p.strip() for p in re.split(r"\n\s*\n", out) if p.strip()]
    if not parts:
        return out, False
    guess = parts[-1]
    out2 = out.rstrip() + f"\n\n<translation>\n{guess}\n</translation>"
    return out2, True


def validate_and_autofix(
    row: Dict,
    idx: int,
    on_missing_translation: str = "error",
    require_reasoning: bool = False,
) -> Optional[Dict]:
    """
    Validate and fix a single JSONL row.

    Returns a dict with normalized text or None if skipped.
    """
    for k in ("instruction", "input", "output"):
        if k not in row or not isinstance(row[k], str) or not row[k].strip():
            logging.warning(f"Skipping item {idx}: missing {k}")
            return None

    instr = normalize_whitespace_keep_newlines(row["instruction"])
    inp   = normalize_whitespace_keep_newlines(row["input"])
    out   = normalize_whitespace_keep_newlines(row["output"])

    src_in = extract_block(inp, "source_text")
    if not src_in:
        logging.warning(f"Item {idx} missing <source_text>")
        return None

    fixes = []

    # Ensure translation block
    trans_out = extract_block(out, "translation")
    if not trans_out:
        if on_missing_translation == "error":
            logging.error(f"Missing <translation> in item {idx}")
            return None
        elif on_missing_translation == "wrap_last_para":
            out, wrapped = wrap_last_paragraph_as_translation(out)
            if not wrapped:
                return None
            fixes.append("wrap_last_para_translation")
        else:  # skip
            return None

    # Optional blocks
    if not extract_block(out, "source_text"):
        fixes.append("inject_source_text")
        out = f"<source_text>\n{src_in}\n</source_text>\n{out}"

    if not extract_block(out, "reasoning"):
        if require_reasoning:
            return None
        fixes.append("inject_reasoning")
        out = re.sub(r"(<translation>)",
                     "<reasoning>\n(omitted)\n</reasoning>\n\\1",
                     out, count=1, flags=re.I)

    inp = ensure_block_lines(inp)
    out = ensure_block_lines(out)
    out = re.sub(r"\s*</translation>\s*$", "\n</translation>", out, flags=re.I)

    return {"instruction": instr, "input": inp, "output": out, "fixes": fixes}


def render_training_text(instr: str, inp: str, out: str) -> str:
    """Concatenate all sections in the training format."""
    return f"{instr}\n\n{inp}\n\n{out}"


def main():
    parser = argparse.ArgumentParser(description="Prepare T2 dataset from raw JSONL.")
    parser.add_argument("--raw_jsonl", required=True)
    parser.add_argument("--out_dir", default="data/prepared")
    parser.add_argument("--dev_ratio", type=float, default=0.1)
    parser.add_argument("--dedupe_by_source", action="store_true")
    parser.add_argument("--require_reasoning", action="store_true")
    parser.add_argument("--on_missing_translation",
                        choices=["error", "skip", "wrap_last_para"],
                        default="error")
    args = parser.parse_args()

    raw_path = Path(args.raw_jsonl)
    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    rows = load_jsonl(raw_path)
    prepped, seen = [], set()
    stats = {"injected_src": 0, "injected_reas": 0, "wrapped_tr": 0, "skipped": 0}

    for i, row in enumerate(rows):
        fixed = validate_and_autofix(
            row, i,
            on_missing_translation=args.on_missing_translation,
            require_reasoning=args.require_reasoning,
        )
        if not fixed:
            stats["skipped"] += 1
            continue

        instr, inp, out = fixed["instruction"], fixed["input"], fixed["output"]
        fixes = fixed["fixes"]

        stats["injected_src"] += "inject_source_text" in fixes
        stats["injected_reas"] += "inject_reasoning" in fixes
        stats["wrapped_tr"] += "wrap_last_para_translation" in fixes

        src_key = extract_block(inp, "source_text") or ""
        if args.dedupe_by_source:
            key = src_key.strip().lower()
            if key in seen:
                stats["skipped"] += 1
                continue
            seen.add(key)

        prepped.append({"id": i, "text": render_training_text(instr, inp, out)})

    if not prepped:
        raise SystemExit("[ERROR] No valid items after preprocessing.")

    # deterministic split
    random.shuffle(prepped)
    n_dev = int(len(prepped) * args.dev_ratio)
    dev, train = prepped[:n_dev], prepped[n_dev:]

    for split, data in {"train": train, "dev": dev}.items():
        out_path = out_dir / f"t2_{split}.jsonl"
        with out_path.open("w", encoding="utf-8") as f:
            for r in data:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        logging.info(f"Saved {split} set: {len(data)} samples → {out_path}")

    logging.info(
        f"Auto-fixes summary: injected_src={stats['injected_src']}, "
        f"injected_reas={stats['injected_reas']}, wrapped_tr={stats['wrapped_tr']}, "
        f"skipped={stats['skipped']}"
    )

if __name__ == "__main__":
    main()
